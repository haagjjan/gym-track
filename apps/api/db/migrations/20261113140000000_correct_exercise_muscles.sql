CREATE TEMPORARY TABLE fix_target ON COMMIT DROP AS
SELECT e.id, e.name FROM exercises e
WHERE e.created_by_user_id IS NULL AND EXISTS (SELECT 1 FROM muscle_fix f WHERE lower(f.name) = lower(e.name));

DELETE FROM exercise_muscle_regions WHERE exercise_id IN (SELECT id FROM fix_target);
INSERT INTO exercise_muscle_regions (exercise_id, muscle_region_id, role)
SELECT t.id, mr.id, f.role
FROM fix_target t
JOIN muscle_fix f ON lower(f.name) = lower(t.name) AND NOT f.is_group
JOIN muscle_regions mr ON mr.slug = f.slug;

-- Set the lead group first: updating it fires a trigger that resets the primary groups.
UPDATE exercises e SET updated_at = now(), primary_muscle_group_id = (
  SELECT coalesce(mr.muscle_group_id, mg.id)
  FROM muscle_fix f
  LEFT JOIN muscle_regions mr ON NOT f.is_group AND mr.slug = f.slug
  LEFT JOIN muscle_groups mg ON f.is_group AND mg.slug = f.slug
  WHERE lower(f.name) = lower(t.name) AND f.role = 'PRIMARY'
  ORDER BY f.ord LIMIT 1)
FROM fix_target t WHERE e.id = t.id;

-- Groups follow the regions: a group is primary when any of its regions is.
DELETE FROM exercise_muscle_groups WHERE exercise_id IN (SELECT id FROM fix_target);
INSERT INTO exercise_muscle_groups (exercise_id, muscle_group_id, role)
SELECT t.id, coalesce(mr.muscle_group_id, mg.id),
  CASE WHEN bool_or(f.role = 'PRIMARY') THEN 'PRIMARY' ELSE 'SECONDARY' END
FROM fix_target t
JOIN muscle_fix f ON lower(f.name) = lower(t.name)
LEFT JOIN muscle_regions mr ON NOT f.is_group AND mr.slug = f.slug
LEFT JOIN muscle_groups mg ON f.is_group AND mg.slug = f.slug
GROUP BY 1, 2;

DELETE FROM exercise_secondary_muscles WHERE exercise_id IN (SELECT id FROM fix_target);
INSERT INTO exercise_secondary_muscles (exercise_id, muscle_group_id)
SELECT exercise_id, muscle_group_id FROM exercise_muscle_groups
WHERE role = 'SECONDARY' AND exercise_id IN (SELECT id FROM fix_target);

DROP TABLE fix_target;
DROP TABLE muscle_fix;
